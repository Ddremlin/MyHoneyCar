    fun describe(code: String): String = known[code] ?: category(code)

    private fun category(code: String): String {
        if (code.length < 5) return ""
        val manufacturer = code[1] != '0' && !(code[0] == 'P' && code[1] == '2')
        val base = when (code[0]) {
            'P' -> when (code[2]) {
                '0', '1', '2' -> "Топливо и воздух"
                '3' -> "Система зажигания / пропуски воспламенения"
                '4' -> "Контроль выбросов"
                '5' -> "Скорость, холостой ход"
                '6' -> "ЭБУ и выходные цепи"
                '7', '8', '9' -> "Трансмиссия"
                else -> "Двигатель и трансмиссия"
            }
            'C' -> "Шасси"
            'B' -> "Кузов"
            'U' -> "Сеть и обмен данными"
            else -> ""
        }
        return if (manufacturer) "$base (код производителя)" else base
    }
