package com.dre.carbook.elm.obd

/**
 * Проверка команд ручного терминала: очистка ввода и распознавание команд,
 * которые меняют что-то в машине или адаптере (сброс, запись, прошивка).
 * Такие команды отправляются только после явного подтверждения.
 */
object CommandGuard {

    const val MAX_LENGTH = 64

    /**
     * Оставляет только печатные ASCII-символы (без \r и \n — иначе одной строкой
     * можно отправить несколько команд), в верхнем регистре, не длиннее [MAX_LENGTH].
     * Пустая строка → null.
     */
    fun normalize(cmd: String): String? =
        cmd.filter { it in ' '..'~' }.trim().uppercase().take(MAX_LENGTH).ifEmpty { null }

    /** Чем опасна команда, или null, если она только читает данные. */
    fun risk(cmd: String): String? {
        val c = cmd.replace(" ", "").uppercase()
        if (c.startsWith("AT") || c.startsWith("ST")) {
            return ADAPTER_RISKS.entries.firstOrNull { c.startsWith(it.key) }?.value
        }
        if (c.length < 2 || !c.all { it in '0'..'9' || it in 'A'..'F' }) return null
        val service = c.take(2)
        // 10 01 — обычный сеанс, безопасен; остальные сеансы (в т.ч. программирование) — нет
        if (service == "10" && c.drop(2).startsWith("01")) return null
        return SERVICE_RISKS[service]
    }

    private val SERVICE_RISKS = mapOf(
        "04" to "Сброс ошибок и статуса готовности систем (Mode 04)",
        "08" to "Управление бортовыми системами (Mode 08)",
        "10" to "Смена диагностического сеанса — может перевести ЭБУ в режим программирования",
        "11" to "Перезагрузка ЭБУ",
        "14" to "Стирание ошибок (UDS)",
        "27" to "Доступ к защищённым функциям ЭБУ (Security Access)",
        "28" to "Отключение связи ЭБУ с другими блоками",
        "2E" to "Запись данных в ЭБУ",
        "2F" to "Управление исполнительными механизмами",
        "31" to "Запуск сервисной процедуры ЭБУ",
        "34" to "Загрузка прошивки в ЭБУ",
        "35" to "Чтение прошивки из ЭБУ (режим загрузчика)",
        "36" to "Передача прошивки",
        "37" to "Завершение передачи прошивки",
        "3B" to "Запись данных в ЭБУ",
        "3D" to "Запись в память ЭБУ",
        "85" to "Отключение записи ошибок в ЭБУ",
    )

    private val ADAPTER_RISKS = linkedMapOf(
        "ATPP" to "Изменение постоянных настроек адаптера (сохраняются после выключения)",
        "ATBRD" to "Смена скорости порта адаптера — связь может пропасть",
        "ATBRT" to "Смена скорости порта адаптера — связь может пропасть",
        "STSBR" to "Смена скорости порта адаптера — связь может пропасть",
        "STBR" to "Смена скорости порта адаптера — связь может пропасть",
    )
}
